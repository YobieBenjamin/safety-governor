"""python -m rtl.conformance: run the spec conformance suite and say honestly what conforms and what does not.

Steps, each self-checking:
  1. every requirement's quote is found verbatim in docs/04 or docs/07 (the table cannot drift from the spec)
  2. every conformance test runs; a test tied to a finding must FAIL BY ASSERTION (the disagreement reproduces)
     and every other test must pass; any other exception is a harness error, never a result
  3. the findings named by tests and the findings written up in FINDINGS.md are the same set
  4. the 87-row catalogue maps to known requirement ids, and matches hardware-and-silicon's report when present
  5. catalogue rows plus conformance tests reach 150
  6. the mutation sample: each one-line mutant must make its requirement's test fail by assertion
  7. REQUIREMENTS.md is what the data says (``--write`` regenerates it), and results/rtl-conformance.md is written
Exit 0 only if all of that holds. Disagreements with the spec do not fail the run; they are listed.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
import time
import warnings
from collections import defaultdict

warnings.filterwarnings("ignore", message=".*created but never used.*")

from . import load_tests                                       # noqa: E402
from . import findings as findings_text, plain_english          # noqa: E402
from .catalogue import CATALOGUE                               # noqa: E402
from .framework import REGISTRY, run_one                      # noqa: E402
from .mutants import MUTANTS                                   # noqa: E402
from .requirements import DOCS, FW, FW_ONLY, OWNER_TEXT, REQ, REQUIREMENTS, RTL, SILICON, normalize  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
REQ_MD = os.path.join(HERE, "REQUIREMENTS.md")
FINDINGS_MD = os.path.join(HERE, "FINDINGS.md")
PLAIN_MD = os.path.join(HERE, "PLAIN-ENGLISH.md")
DIFF_CLASSES = {"agree": 3690, "F-01": 253, "F-02": 3, "F-03": 54}   # the random run's numbers FINDINGS quotes
RESULT_MD = os.path.join(ROOT, "results", "rtl-conformance.md")
TARGET = 150


def find_catalogue_report() -> str | None:
    for base in (os.environ.get("HARDWARE_AND_SILICON"), os.path.join(os.path.dirname(ROOT), "hardware-and-silicon")):
        if base and os.path.exists(os.path.join(base, "results", "report.json")):
            return os.path.join(base, "results", "report.json")
    return None


def tests_by_req() -> dict[str, list]:
    out = defaultdict(list)
    for t in REGISTRY:
        for r in t.reqs:
            out[r].append(t)
    return out


def catalogue_by_req() -> dict[str, list[str]]:
    out = defaultdict(list)
    for name, (_, reqs) in CATALOGUE.items():
        for r in reqs:
            out[r].append(name)
    return out


def requirements_md() -> str:
    tb, cb = tests_by_req(), catalogue_by_req()
    n_tests = len(REGISTRY)
    lines = [
        "# Requirements table: what the spec says the hard core must do",
        "",
        "Generated by `python -m rtl.conformance --write` from `requirements.py`, the test registry and",
        "`catalogue.py`; the default run fails if this file is stale. Every quote below was checked verbatim",
        "against `docs/04-specification.md` (S) or `docs/07-verification-plan.md` (V), backticks and line",
        "breaks ignored.",
        "",
        "Owners: **RTL** the hard core (`rtl/governor_rtl`, `GovernorCore` in `top.py`) decides it.",
        f"**FW** {OWNER_TEXT[FW]}. **FW-ONLY** {OWNER_TEXT[FW_ONLY]}. **SILICON** {OWNER_TEXT[SILICON]}.",
        "Findings (F-nn) are the tests that reproduce a disagreement; see `FINDINGS.md`.",
        "",
        "| Id | Source | The spec's words | Block | Owner | Conformance tests | Catalogue rows |",
        "|---|---|---|---|---|---|---|",
    ]
    for rid, doc, sec, quote, block, owner in REQUIREMENTS:
        ts = tb.get(rid, [])
        cell = "<br>".join(f"`{t.name}`" + (f" ({t.finding})" if t.finding else "") for t in ts) or "none"
        rows = cb.get(rid, [])
        lines.append(f"| {rid} | {doc} §{sec} | {quote.replace('|', '/')} | {block} | {owner} | {cell} | {len(rows) or ''} |")
    lines += [
        "",
        "## The catalogue, row by row",
        "",
        "The 75-attack, 12-baseline catalogue in `hardware-and-silicon` (`hardware_ref`, `results/report.json`).",
        "Every row runs against the reference software stack, so in the catalogue every row is decided by the",
        "reference gate. The owner column says which layer of the governor would decide the same thing.",
        "",
        "| Row | Governor-side owner | Requirements |",
        "|---|---|---|",
    ]
    for name, (owner, reqs) in CATALOGUE.items():
        lines.append(f"| `{name}` | {owner} | {', '.join(reqs)} |")
    by_owner = defaultdict(int)
    for owner, _ in CATALOGUE.values():
        by_owner[owner] += 1
    lines += [
        "",
        "## The count",
        "",
        f"Catalogue rows: {len(CATALOGUE)} ({', '.join(f'{v} {k}' for k, v in sorted(by_owner.items()))}).",
        f"Conformance tests in `rtl/conformance`: {n_tests}, each tied to at least one requirement id.",
        f"Total: {len(CATALOGUE) + n_tests} (target {TARGET}).",
        "",
        "Be clear about what the two halves are. The catalogue rows exercise the reference software stack, not",
        "the RTL; they count toward the total because the brief counts them, not because they test the chip.",
        "The conformance tests are the ones that run against the Amaranth RTL (and, for the differential ones,",
        "against govsim beside it).",
        "",
    ]
    return "\n".join(lines)


def run_mutants() -> list[dict]:
    out = []
    env = dict(os.environ, PYTHONWARNINGS="ignore")
    for i, (req, src, old, new, test) in enumerate(MUTANTS):
        p = subprocess.run([sys.executable, "-m", "rtl.conformance.mutants", str(i)], capture_output=True, text=True,
                           cwd=ROOT, env=env, timeout=600)
        try:
            r = json.loads(p.stdout.strip().splitlines()[-1])
        except (ValueError, IndexError):
            r = {"i": i, "status": "error", "detail": (p.stderr or p.stdout)[-300:]}
        r.update(req=req, src=src, test=test, old=old, new=new)
        out.append(r)
        mark = "caught by assertion" if r["status"] == "assert" else ("SURVIVED" if r["status"] == "pass" else "HARNESS ERROR")
        print(f"  mutant {i + 1:2d}/{len(MUTANTS)} {req} {src:15s} {mark}")
    return out


def main(argv: list[str]) -> int:
    quick, write = "--quick" in argv, "--write" in argv
    t0 = time.time()
    problems: list[str] = []

    # 1. quotes
    docs = {k: normalize(open(os.path.join(ROOT, v), encoding="utf-8").read()) for k, v in DOCS.items()}
    for rid, doc, _, quote, _, _ in REQUIREMENTS:
        if normalize(quote) not in docs[doc]:
            problems.append(f"{rid}: quote not found in {DOCS[doc]}: {quote!r}")
    print(f"[1] requirements: {len(REQUIREMENTS)} rows, quotes checked against the spec: "
          f"{'all found' if not problems else f'{len(problems)} missing'}")

    # 2. tests
    load_tests()
    for t in REGISTRY:
        for r in t.reqs:
            if r not in REQ:
                problems.append(f"{t.name}: unknown requirement {r}")
    outcomes = [run_one(t) for t in REGISTRY]
    passed = [o for o in outcomes if o.status == "pass" and not o.test.finding]
    reproduced = [o for o in outcomes if o.status == "assert" and o.test.finding]
    for o in outcomes:
        if o.test.finding and o.status == "pass":
            problems.append(f"{o.test.name}: finding {o.test.finding} no longer reproduces; update FINDINGS.md")
        elif not o.test.finding and o.status == "assert":
            problems.append(f"{o.test.name}: FAILED: {o.detail}")
        elif o.status == "error":
            problems.append(f"{o.test.name}: HARNESS ERROR (not a result): {o.detail}")
    print(f"[2] conformance tests: {len(outcomes)} run; {len(passed)} conform; {len(reproduced)} reproduce a recorded "
          f"disagreement; {len(outcomes) - len(passed) - len(reproduced)} other")

    # 3. findings file
    # a closed finding keeps its section (the record of what was wrong) but has "(closed)" in its heading;
    # its reproducer has become an ordinary conformance test that guards the fix
    written = {f for f, rest in re.findall(r"^## (F-\d\d)(.*)$", findings_text.TEXT, re.M) if "(closed)" not in rest}
    named = {t.finding for t in REGISTRY if t.finding}
    for f in sorted(named - written):
        problems.append(f"{f} has reproducer tests but no section in FINDINGS.md")
    for f in sorted(written - named):
        problems.append(f"{f} is in FINDINGS.md but no test reproduces it")
    print(f"[3] findings: {len(named)} reproduced by tests, {len(written)} written up")

    # 4. catalogue
    for name, (_, reqs) in CATALOGUE.items():
        for r in reqs:
            if r not in REQ:
                problems.append(f"catalogue {name}: unknown requirement {r}")
    report = find_catalogue_report()
    if report:
        data = json.load(open(report, encoding="utf-8"))
        names = {o["name"] for o in data["outcomes"]}
        if names != set(CATALOGUE):
            problems.append(f"catalogue mismatch with {report}: missing {sorted(names - set(CATALOGUE))}, "
                            f"extra {sorted(set(CATALOGUE) - names)}")
        cat_note = (f"matches {os.path.relpath(report, os.path.dirname(ROOT))} ({data['attacks_blocked']}/{data['attacks']} "
                    f"attacks blocked, {data['baselines_allowed']}/{data['baselines']} baselines allowed, passed={data['passed']})")
    else:
        cat_note = "hardware-and-silicon clone not found (set HARDWARE_AND_SILICON); name cross-check skipped"
    print(f"[4] catalogue: {len(CATALOGUE)} rows mapped; {cat_note}")

    # 5. count
    total = len(CATALOGUE) + len(REGISTRY)
    if total < TARGET:
        problems.append(f"catalogue rows + conformance tests = {total}, below {TARGET}")
    print(f"[5] count: {len(CATALOGUE)} catalogue rows + {len(REGISTRY)} conformance tests = {total} (target {TARGET})")

    # 6. mutants
    mut: list[dict] = []
    if quick:
        print("[6] mutation sample: skipped (--quick)")
    else:
        status = {o.test.name: o.status for o in outcomes}
        for req, _, _, _, test in MUTANTS:
            if status.get(test) != "pass":
                problems.append(f"mutant for {req}: its test {test} does not pass on the unmutated RTL")
        print(f"[6] mutation sample: {len(MUTANTS)} one-line mutants, {len({m[0] for m in MUTANTS})} requirements")
        mut = run_mutants()
        for m in mut:
            if m["status"] != "assert":
                problems.append(f"mutant {m['i'] + 1} ({m['req']}, {m['src']}): {m['status']} {m.get('detail', '')}")
        print(f"    caught by assertion: {sum(m['status'] == 'assert' for m in mut)}/{len(mut)}")

    diff = next(o for o in outcomes if o.test.name == "test_diff_mailbox_random_frames_only_known_disagreements")
    if diff.extra and diff.extra.get("classes") != DIFF_CLASSES:
        problems.append(f"the random mailbox run gave {diff.extra.get('classes')}; FINDINGS quotes {DIFF_CLASSES}")

    for quoted in (f"runs {len(REGISTRY)} conformance tests", f"(87 + {len(REGISTRY)} = {total})", f"plants {len(MUTANTS)} one-line"):
        if quoted not in plain_english.TEXT:
            problems.append(f"plain_english.py no longer matches the suite (expected the words {quoted!r})")

    # 7. the generated files and the report
    for path, text in ((REQ_MD, requirements_md()), (FINDINGS_MD, findings_text.TEXT), (PLAIN_MD, plain_english.TEXT)):
        rel = os.path.relpath(path, ROOT)
        if write:
            open(path, "w", encoding="utf-8").write(text)
            print(f"[7] wrote {rel}")
        elif not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
            problems.append(f"{rel} is stale: run python -m rtl.conformance --write")
        else:
            print(f"[7] {rel} is current")

    table = coverage(outcomes)
    print()
    print(table["console"])
    write_report(outcomes, mut, table, cat_note, total, problems, quick)
    print()
    if problems:
        print("RESULT: FAIL")
        for p in problems:
            print("  - " + p)
    else:
        print(f"RESULT: PASS (the suite does what it claims; {len(named)} disagreements with the spec are recorded "
              f"in FINDINGS.md and listed above)")
    print(f"wrote {os.path.relpath(RESULT_MD, ROOT)} in {time.time() - t0:.0f} s")
    return 1 if problems else 0


def coverage(outcomes) -> dict:
    by = defaultdict(list)
    for o in outcomes:
        for r in o.test.reqs:
            by[r].append(o)
    cb = catalogue_by_req()
    rows = []
    for rid, _, _, quote, block, owner in REQUIREMENTS:
        os_ = by.get(rid, [])
        fails = sorted({o.test.finding for o in os_ if o.test.finding and o.status == "assert"})
        conform = sum(1 for o in os_ if o.status == "pass" and not o.test.finding)
        if fails:
            verdict = "DISAGREES " + ",".join(fails)
        elif conform:
            verdict = "conforms"
        elif cb.get(rid):
            verdict = "catalogue only"
        else:
            verdict = "not covered"
        rows.append((rid, owner, block, conform, len(cb.get(rid, [])), verdict, quote))
    counts = defaultdict(lambda: defaultdict(int))
    for r in rows:
        counts[r[1]][r[5].split()[0]] += 1
    console = ["Requirements coverage by owner. 'disagree' means a recorded finding touches the row; the finding says",
               "whether the RTL, the model or the spec text is the one that is off (FINDINGS.md)."]
    for owner in (RTL, FW, FW_ONLY, SILICON):
        c = counts[owner]
        console.append(f"  {owner:8s} {sum(c.values()):3d} rows: {c['conforms']:3d} conform, {c['DISAGREES']:2d} disagree, "
                       f"{c['catalogue']:2d} catalogue only, {c['not']:2d} not covered")
    console.append("")
    console.append(f"  {'id':6s} {'owner':8s} {'tests':>5s} {'cat':>4s}  verdict")
    for rid, owner, block, conform, ncat, verdict, _ in rows:
        if owner in (RTL, FW) or verdict.startswith("DISAGREES"):
            console.append(f"  {rid:6s} {owner:8s} {conform:5d} {ncat:4d}  {verdict}")
    return {"rows": rows, "console": "\n".join(console), "counts": counts}


def write_report(outcomes, mut, table, cat_note, total, problems, quick) -> None:
    import platform
    findings = defaultdict(list)
    for o in outcomes:
        if o.test.finding:
            for f in o.test.finding.split(","):
                findings[f].append(o)
    diff = next((o for o in outcomes if o.test.name == "test_diff_mailbox_random_frames_only_known_disagreements"), None)
    cap = next((o for o in outcomes if o.test.name == "test_diff_cap_table_random_against_model_switch"), None)
    L = ["# RTL spec conformance", "",
         f"`python -m rtl.conformance{' --quick' if quick else ''}` on Python {platform.python_version()}. "
         f"**Result: {'FAIL' if problems else 'PASS'}** (PASS means the suite does what it says: every conforming test "
         f"passes, every recorded disagreement reproduces by assertion{', every mutant is caught' if not quick else ''}). "
         "Disagreements with the spec are findings, listed below; they do not fail the run.", ""]
    n_pass = sum(1 for o in outcomes if o.status == "pass" and not o.test.finding)
    n_rep = sum(1 for o in outcomes if o.status == "assert" and o.test.finding)
    L += [f"- Requirements: {len(REQUIREMENTS)} (from docs/04 and docs/07, quotes checked verbatim)",
          f"- Conformance tests: {len(outcomes)}; {n_pass} conform, {n_rep} reproduce a disagreement",
          f"- Catalogue: {len(CATALOGUE)} rows mapped; {cat_note}",
          f"- Catalogue rows + conformance tests: {total} (target {TARGET})"]
    if mut:
        L.append(f"- Mutation sample: {sum(m['status'] == 'assert' for m in mut)}/{len(mut)} one-line mutants caught by "
                 f"assertion, over {len({m['req'] for m in mut})} requirements")
    if diff and diff.extra:
        L.append(f"- Mailbox differential: {diff.extra['frames']} random frames, classes {diff.extra['classes']}")
    if cap and cap.extra:
        L.append(f"- Capability table differential: {cap.extra}")
    if problems:
        L += ["", "## Problems", ""] + [f"- {p}" for p in problems]
    L += ["", "## Disagreements (findings)", "", "| Finding | Reproducer | What the RTL or model did |", "|---|---|---|"]
    for f in sorted(findings):
        for o in findings[f]:
            L.append(f"| {f} | `{o.test.name}` | {o.status}: {o.detail.replace('|', '/')} |")
    if diff and diff.extra:
        L += ["", "First example of each mailbox disagreement class in the random run:", ""]
        for k, v in sorted(diff.extra["examples"].items()):
            L.append(f"- {k}: {v}")
    L += ["", "## Coverage by requirement", "", "| Id | Owner | Block | Conforming tests | Catalogue rows | Verdict |",
          "|---|---|---|---|---|---|"]
    for rid, owner, block, conform, ncat, verdict, _ in table["rows"]:
        L.append(f"| {rid} | {owner} | {block} | {conform} | {ncat} | {verdict} |")
    if mut:
        L += ["", "## Mutation sample", "", "| # | Requirement | File | Mutant | Test | Outcome |", "|---|---|---|---|---|---|"]
        for m in mut:
            esc = lambda t: t.replace("|", "\\|")      # noqa: E731
            L.append(f"| {m['i'] + 1} | {m['req']} | {m['src']} | `{esc(m['old'])}` to `{esc(m['new'])}` | `{m['test']}` | "
                     f"{'caught by assertion' if m['status'] == 'assert' else m['status']} |")
    L += ["", "## Every test", "", "| Test | Requirements | Outcome | Seconds |", "|---|---|---|---|"]
    for o in outcomes:
        tag = ("reproduces " + o.test.finding) if (o.test.finding and o.status == "assert") else o.status
        L.append(f"| `{o.test.name}` | {', '.join(o.test.reqs)} | {tag} | {o.seconds:.1f} |")
    os.makedirs(os.path.dirname(RESULT_MD), exist_ok=True)
    open(RESULT_MD, "w", encoding="utf-8").write("\n".join(L) + "\n")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
