"""Sweep the halt-loop timing simulation and write hw/loop/results.md.

    python3 hw/loop/run_loop.py

For N in {8, 36, 72}, the opening governor at the first, middle and last position, hop
lengths of 1 m and 3 m, and temperatures of 0 C and 85 C (plus one wire break at the middle
hop per N at the long, hot corner), the script generates the ngspice deck with
loop_netlist.py, runs it, reads the time at which every governor's sense voltage falls
through the comparator threshold, and adds the digital path:

    comparator latency          1 us     assumed
    sampling phase uncertainty  100 us   up to one sense period (the loss lands just after a sample)
    debounce                    200 us   two sense periods, from the spec (04-specification.md section 9)
    lever assertion             10 us    assumed, PWRBRK# driver from loop_lost to the pin

so the worst case from electrical loss to loop_lost is 300 us and the digital path is 311 us.
The bound is 1 ms end to end (02-safety-fabric.md section 1). The script exits non-zero if
any configuration misses the bound or any governor never sees the loss.
"""

from __future__ import annotations

import shutil
import sys
import time
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import loop_netlist as ln  # noqa: E402

COMPARATOR_LATENCY_S = 1e-6     # assumed
SENSE_PERIOD_S = 100e-6         # from the spec
DEBOUNCE_PERIODS = 2            # from the spec: loss declared after two sense periods
PHASE_PERIODS = 1               # assumed worst case: up to one period before the first sample
LEVER_ASSERT_S = 10e-6          # assumed: PWRBRK# driver
BOUND_S = 1e-3                  # from the spec

SWEEP_N = (8, 36, 72)
SWEEP_POSITION = ("first", "middle", "last")
SWEEP_HOP_M = (1.0, 3.0)
SWEEP_TEMP_C = (0.0, 85.0)
RESULTS = HERE / "results.md"


def digital_path_s() -> float:
    """Worst-case time from the sense voltage crossing the threshold to the halt output."""
    return COMPARATOR_LATENCY_S + (DEBOUNCE_PERIODS + PHASE_PERIODS) * SENSE_PERIOD_S + LEVER_ASSERT_S


def position_index(n: int, position: str) -> int:
    return {"first": 1, "middle": (n + 1) // 2, "last": n}[position]


@dataclass
class Row:
    label: str
    n: int
    opens: str
    hop_m: float
    temp_c: float
    propagation_s: float | None
    last_governor: int | None
    v_sense_nom: float | None

    @property
    def total_s(self) -> float | None:
        return None if self.propagation_s is None else self.propagation_s + digital_path_s()

    @property
    def margin_s(self) -> float | None:
        return None if self.total_s is None else BOUND_S - self.total_s

    @property
    def passed(self) -> bool:
        return self.total_s is not None and self.total_s <= BOUND_S


def configurations() -> list[ln.LoopParams]:
    out = []
    for n in SWEEP_N:
        for pos in SWEEP_POSITION:
            for hop in SWEEP_HOP_M:
                for temp in SWEEP_TEMP_C:
                    out.append(ln.LoopParams(n=n, open_gov=position_index(n, pos), hop_m=hop, temp_c=temp))
        out.append(ln.LoopParams(n=n, open_gov=None, break_hop=max(1, n // 2),
                                 hop_m=SWEEP_HOP_M[-1], temp_c=SWEEP_TEMP_C[-1]))
    return out


def run_one(p: ln.LoopParams) -> Row:
    r = ln.simulate(p)
    if p.open_gov is not None:
        name = {1: "first", p.n: "last"}.get(p.open_gov, "middle")
        opens = f"governor {p.open_gov} ({name})"
    else:
        opens = f"wire break, hop {p.break_hop}"
    label = f"N={p.n}, {opens}, {p.hop_m:g} m hops, {p.temp_c:g} C"
    return Row(label, p.n, opens, p.hop_m, p.temp_c, r.propagation_s, r.last_governor, r.v_sense_nom)


def us(x: float | None) -> str:
    return "none" if x is None else f"{x * 1e6:.2f}"


def table(rows: list[Row]) -> str:
    head = ("| N | Opens | Hop (m) | Temp (C) | Last to see loss | Electrical propagation (us) "
            "| Digital detection (us) | Total (us) | Margin to 1 ms (us) | Result |\n"
            "|---|---|---|---|---|---|---|---|---|---|\n")
    body = "".join(
        f"| {r.n} | {r.opens} | {r.hop_m:g} | {r.temp_c:g} | "
        f"{'none' if r.last_governor is None else 'governor ' + str(r.last_governor)} | "
        f"{us(r.propagation_s)} | {us(digital_path_s())} | {us(r.total_s)} | {us(r.margin_s)} | "
        f"{'pass' if r.passed else 'FAIL'} |\n" for r in rows)
    return head + body


def report(rows: list[Row], elapsed: float, ngspice_version: str) -> str:
    worst = max((r for r in rows if r.total_s is not None), key=lambda r: r.total_s, default=None)
    all_pass = all(r.passed for r in rows)
    lines = [
        "# Halt loop timing: simulation results",
        "",
        "Generated by `python3 hw/loop/run_loop.py` (do not edit; rerun instead). "
        f"{len(rows)} ngspice runs in {elapsed:.1f} s with {ngspice_version}.",
        "",
        "**What was measured.** For each configuration one governor opens its switch (or one hop's "
        "wire breaks) at 20 us. Electrical propagation is the time from that instant to the moment "
        "the slowest governor's sense voltage falls through the comparator threshold "
        f"({ln.LoopParams().v_threshold * 1e3:.0f} mV, 50 percent of the nominal "
        f"{ln.LoopParams().v_sense_nom * 1e3:.0f} mV). Digital detection is the worst-case path from "
        f"that crossing to the halt output: comparator {us(COMPARATOR_LATENCY_S)} us, sampling phase "
        f"up to {PHASE_PERIODS} sense period, debounce {DEBOUNCE_PERIODS} sense periods of "
        f"{us(SENSE_PERIOD_S)} us, lever driver {us(LEVER_ASSERT_S)} us: {us(digital_path_s())} us. "
        f"The bound is {us(BOUND_S)} us end to end.",
        "",
        "**Circuit.** 24 V driver with a series resistor sized for 20 mA at 25 C; per governor a "
        "voltage-controlled switch (Ron 1 ohm, Roff 1 Mohm) and a 10 ohm sense resistor; per hop a "
        "twisted-pair RC pi section at 0.1 ohm/m per conductor and 50 pF/m, no inductance; copper at "
        "3930 ppm/K, driver resistor 200 ppm/K, sense resistor 100 ppm/K; switch edge 100 ns; "
        "`.tran 1u` with a 100 ns maximum internal step. See `docs/11-loop-timing.md`.",
        "",
        table(rows),
    ]
    if worst is not None:
        lines.append(f"**Worst case:** {worst.label}: electrical propagation {us(worst.propagation_s)} us, "
                     f"total {us(worst.total_s)} us, margin {us(worst.margin_s)} us to the 1 ms bound.")
    lines += ["", f"**Result: {'PASS' if all_pass else 'FAIL'}** "
              + ("(every configuration halts every governor inside 1 ms)" if all_pass
                 else "(at least one configuration misses the bound or a governor never saw the loss)"),
              ""]
    return "\n".join(lines)


def main() -> int:
    if shutil.which(ln.NGSPICE) is None:
        print("ngspice not found on PATH; install ngspice (version 42 was used) and rerun", file=sys.stderr)
        return 2
    import subprocess
    ver = subprocess.run([ln.NGSPICE, "-v"], capture_output=True, text=True).stdout
    ngspice_version = next((l.strip("* ").strip() for l in ver.splitlines() if "ngspice-" in l), "ngspice")
    t0 = time.perf_counter()
    rows = []
    for p in configurations():
        row = run_one(p)
        rows.append(row)
        print(f"{row.label:48s} propagation {us(row.propagation_s):>7} us  total {us(row.total_s):>7} us  "
              f"{'pass' if row.passed else 'FAIL'}")
    elapsed = time.perf_counter() - t0
    text = report(rows, elapsed, ngspice_version)
    RESULTS.write_text(text)
    all_pass = all(r.passed for r in rows)
    print(f"\n{len(rows)} configurations in {elapsed:.1f} s; wrote {RESULTS}")
    print("PASS: every configuration halts every governor inside 1 ms" if all_pass
          else "FAIL: see results.md")
    return 0 if all_pass else 1


if __name__ == "__main__":
    sys.exit(main())
